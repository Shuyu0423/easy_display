#ifndef CST816_H__
#define CST816_H__

#include "touch_driver.h"

#define CST816_DEFAULT_ADDR (0x15U)

#define CST816_CHIP_ID_1 (0xB4U)
#define CST816_CHIP_ID_2 (0xB5U)
#define CST816_CHIP_ID_3 (0xB6U)

#define CST816_REG_GESTURE_ID (0x01U)
#define CST816_REG_FINGER_NUM (0x02U)
#define CST816_REG_XPOS_H (0x03U)
#define CST816_REG_XPOS_L (0x04U)
#define CST816_REG_YPOS_H (0x05U)
#define CST816_REG_YPOS_L (0x06U)
#define CST816_REG_SLEEP_MODE (0xA5U)
#define CST816_REG_CHIP_ID (0xA7U)
#define CST816_REG_PROJECT_ID (0xA8U)
#define CST816_REG_FW_VERSION (0xA9U)
#define CST816_REG_MOTION_MASK (0xECU)
#define CST816_REG_IRQ_PULSE_WIDTH (0xEDU)
#define CST816_REG_NOR_SCAN_PER (0xEEU)
#define CST816_REG_LP_SCAN_RAW1_H (0xF0U)
#define CST816_REG_LP_SCAN_RAW1_L (0xF1U)
#define CST816_REG_LP_SCAN_RAW2_H (0xF2U)
#define CST816_REG_LP_SCAN_RAW2_L (0xF3U)
#define CST816_REG_LP_AUTO_WAKE_TIME (0xF4U)
#define CST816_REG_LP_SCAN_TH (0xF5U)
#define CST816_REG_LP_SCAN_WIN (0xF6U)
#define CST816_REG_LP_SCAN_FREQ (0xF7U)
#define CST816_REG_LP_SCAN_IDAC (0xF8U)
#define CST816_REG_AUTOSLEEP_TIME (0xF9U)
#define CST816_REG_IRQ_CTL (0xFAU)
#define CST816_REG_DEBOUNCE_TIME (0xFBU)
#define CST816_REG_LONG_PRESS_TIME (0xFCU)
#define CST816_REG_IO_CTL (0xFDU)
#define CST816_REG_DIS_AUTOSLEEP (0xFEU)

#define CST816_IRQ_EN_TOUCH (0x40U)
#define CST816_IRQ_EN_CHANGE (0x20U)
#define CST816_IRQ_EN_MOTION (0x10U)
#define CST816_DEFAULT_IRQ_CTL (CST816_IRQ_EN_TOUCH | CST816_IRQ_EN_CHANGE)
#define CST816_DEFAULT_AUTOSLEEP_TIME (5U)

#define CST816_GESTURE_NONE (0x00U)
#define CST816_GESTURE_SLIDE_UP (0x01U)
#define CST816_GESTURE_SLIDE_DOWN (0x02U)
#define CST816_GESTURE_SLIDE_LEFT (0x03U)
#define CST816_GESTURE_SLIDE_RIGHT (0x04U)
#define CST816_GESTURE_SINGLE_CLICK (0x05U)
#define CST816_GESTURE_DOUBLE_CLICK (0x0BU)
#define CST816_GESTURE_LONG_PRESS (0x0CU)

#define CST816_POINT_EVENT_PRESS (0x00U)
#define CST816_POINT_EVENT_RELEASE (0x01U)
#define CST816_POINT_EVENT_CONTACT (0x02U)
#define CST816_POINT_EVENT_NONE (0x03U)
#define CST816_POINT_EVENT_SHIFT (6U)
#define CST816_POINT_COORD_H_MASK (0x0FU)

#define CST816_SLEEP_CMD (0x03U)

typedef struct {
    uint8_t chip_id;
    uint8_t project_id;
    uint8_t fw_version;
    uint8_t last_pressed;
} CST816_CONTEXT;

uint8_t cst816_register(TOUCH_DEVICE *dev, TOUCH_BUS_OPS *bus, uint16_t width, uint16_t height);
const TOUCH_CONTROLLER *cst816_get_controller(void);
CST816_CONTEXT *cst816_get_context(void);

#endif
